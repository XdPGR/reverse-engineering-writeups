keys = [0x31, 0x38, 0x3f, 0x46, 0x4d, 0x54, 0x5b, 0x62, 0x69, 0x70, 0x77, 0x7e]
targets = [0x1b, 0x78, 0x4a, 0x3b, 0x30, 0x33, 0xb1, 0x0a, 0xc1, 0x4a, 0x68, 0xf1]

password = ""
for i in range(12):
    target = targets[i]
    key = keys[i]
    ror_result = ((target >> 3) | (target << 5)) & 0xFF
    original_char_code = ror_result ^ key
    password += chr(original_char_code)

print(password)
